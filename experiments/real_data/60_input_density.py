"""What the `--n-profiles` cap actually delivers, per month.

`--n-profiles N` is a CAP passed to `_select_profiles`, which returns the whole
pool untouched when the pool is smaller than N.  Calling an arm "128 profiles
per month" therefore overstates it whenever the month cannot supply 128 -- and
in these cohorts most months cannot.  Training is further reduced because
`training_rows` withholds ~30 % of the month's floats to serve as targets, so
the input is drawn only from what remains.

The selection is deterministic given (cohort, cap, seed, month), so the realised
counts can be measured once here and reused to label the tables, rather than
each table repeating the assumption that cap == count.

  .venv/bin/python experiments/real_data/60_input_density.py
"""
from __future__ import annotations

import argparse, json, os, sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "src"))
import warnings; warnings.filterwarnings("ignore")

import numpy as np

from ocean_tokenizer.argo_obs import ArgoCohort, _select_profiles, training_rows

ap = argparse.ArgumentParser()
ap.add_argument("--regions", nargs="+", default=["gulfstream", "npac_gyre"])
ap.add_argument("--caps", nargs="+", type=int, default=[24, 128])
ap.add_argument("--splits", nargs="+", default=["train", "development"])
ap.add_argument("--seed", type=int, default=1234)
args = ap.parse_args()

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
out: dict = {}
rows: list = []

for region in args.regions:
    c = ArgoCohort.load(os.path.join(ROOT, "data", "argo_cohort",
                                     f"{region}_ext.nc"))
    for cap in args.caps:
        for split in args.splits:
            got = []
            for m in [int(x) for x in c.months_in(split)]:
                if split == "train":
                    pr, tr = training_rows(
                        c, m, 0, cap, np.random.default_rng([args.seed, m, 0]))
                    if tr.size == 0:
                        continue
                else:
                    pr = _select_profiles(
                        c, c.month(m, float_split="cohort_float"), cap,
                        np.random.default_rng([args.seed, m, 0]))
                if pr.size:
                    got.append(int(pr.size))
            if not got:
                continue
            a = np.array(got)
            d = {"region": region, "cap": cap, "split": split,
                 "n_months": int(a.size), "mean": float(a.mean()),
                 "median": float(np.median(a)), "min": int(a.min()),
                 "max": int(a.max()),
                 "frac_at_cap": float((a >= cap).mean())}
            out.setdefault(region, {}).setdefault(str(cap), {})[split] = d
            rows.append(d)
            print(f"{region:11s} cap={cap:4d} {split:12s} n_months={d['n_months']:4d}  "
                  f"mean={d['mean']:6.1f} median={d['median']:5.0f} "
                  f"min={d['min']:4d} max={d['max']:4d}  "
                  f"at cap={d['frac_at_cap']:.2f}", flush=True)

L = ["# Realised input density per month", "",
     "_Generated by `experiments/real_data/60_input_density.py`._", "",
     "`--n-profiles N` is a cap, not a count: `_select_profiles` returns the "
     "whole pool when the pool is smaller than N. Training is lower still "
     "because `training_rows` withholds ~30 % of each month's floats to serve "
     "as targets, so the input is drawn only from the remainder.", "",
     "| region | cap | split | months | mean | median | min | max | at cap |",
     "|---|---:|---|---:|---:|---:|---:|---:|---:|"]
for d in rows:
    L.append(f"| {d['region']} | {d['cap']} | {d['split']} | {d['n_months']} | "
             f"{d['mean']:.1f} | {d['median']:.0f} | {d['min']} | {d['max']} | "
             f"{d['frac_at_cap']:.2f} |")
L += ["", "**Consequence for the tables.** The arm labelled 128 delivers a "
      "mean of roughly 81-89 profiles in training and 87-117 at evaluation, so "
      "the density contrast is about 24 vs 85, not 24 vs 128. The 24 arm does "
      "reach its cap in essentially every month, so only the upper arm is "
      "overstated by its label.", ""]

os.makedirs(os.path.join(ROOT, "reports", "real_data"), exist_ok=True)
p_md = os.path.join(ROOT, "reports", "real_data", "input_density.md")
open(p_md, "w").write("\n".join(L))
p_js = os.path.join(ROOT, "outputs", "input_density.json")
json.dump(out, open(p_js, "w"), indent=1)
print(f"\nwrote {p_md}\nwrote {p_js}")
