"""Tabulate the query-anchored fusion runs against the rows they are compared with.

Reads ``outputs/audit/<region>/<tag>/summary_seed*.json`` written by
``67_anchored_fusion.py`` and the stored summaries of the reference rows (fixed
baselines, the earlier models). Prints mean +- sd over seeds; ``--write`` also
saves the tables as ``reports/real_data/anchored_fusion_<region>.md``.

  .venv/bin/python experiments/real_data/68_anchored_report.py --region synthetic
  .venv/bin/python experiments/real_data/68_anchored_report.py --region global --write
"""
from __future__ import annotations

import argparse, glob, json, os

import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--region", default="global", choices=["global", "synthetic"])
ap.add_argument("--tags", default=None, help="comma-separated; default every anc_* run")
ap.add_argument("--subdir", default=None,
                help="read runs from outputs/audit/<region>/<subdir>/ (a cohort's own folder)")
ap.add_argument("--detail", action="store_true", help="also print learned scales and curves")
ap.add_argument("--write", action="store_true")
args = ap.parse_args()

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
BASE = os.path.join(ROOT, "outputs", "audit", args.region, *( [args.subdir] if args.subdir else []))
CH = ("TEMP", "SALT")


def runs(tag, base=BASE):
    return [json.load(open(f)) for f in sorted(glob.glob(os.path.join(base, tag, "summary_seed*.json")))]


def cell(vals, digits=4):
    vals = np.asarray(vals, float)
    if vals.size == 0:
        return "-"
    if vals.size == 1:
        return f"{vals[0]:.{digits}f}"
    return f"{vals.mean():.{digits}f} ± {vals.std(ddof=0):.{digits}f}"


def row(label, scores_list, split="development", n=None):
    """One table row from a list of ``scores`` blocks (one per seed)."""
    get = lambda ch, key: [s[split][ch][key] for s in scores_list if split in s]
    copy = [s["copy_unseen"]["TEMP"]["J"] for s in scores_list if "copy_unseen" in s]
    return (f"| {label} | {n or len(scores_list)} | {cell(get('TEMP', 'rmse_physical'))} | "
            f"{cell(get('SALT', 'rmse_physical'))} | {cell(get('TEMP', 'J'), 3)} | "
            f"{cell(get('SALT', 'J'), 3)} | {cell(copy, 3)} |")


lines = [f"# Query-anchored fusion — {args.region}", "",
         "<!-- generated by experiments/real_data/68_anchored_report.py -->", "",
         "Development split, the cells of the audit's runs. RMSE in physical units; J = RMSE / RMSE of "
         "a zero-anomaly prediction in train-normalized anomaly units (lower is better); copy = J for TEMP when the queries are "
                  "input profiles of the previously used development months. Mean ± sd over seeds.", "",
         "These are development reconstruction results, not independent confirmation or causal forecasts. "
         "Monthly and daily satellite configurations use different information. Seed counts are shown explicitly.", "",
         *(["The historical `real_exact_r500_g1` row uses an exact-anomaly evaluation fingerprint "
            "(981735 valid values per variable), whereas the matched cell-anomaly rows use 976452. "
            "It is included for historical context and must not be ranked as a matched comparison.", ""]
           if args.region == "global" and not args.subdir else []),
         "| method | seeds | TEMP (°C) | SALT (PSU) | J TEMP | J SALT | copy J |",
         "|---|---|---|---|---|---|---|"]

# ---- reference rows
if args.region == "synthetic" and not args.subdir:
    fb = json.load(open(os.path.join(BASE, "fixed_baselines", "summary.json")))["baselines"]
    for name, lab in (("climatology", "climatology"), ("nearest_profile", "nearest profile"),
                      ("oi", "OI, tuned per variable and depth band")):
        lines.append(row(lab, [fb[name]["scores"]], n=1))
    for tag, lab in (("pointwise_mlp", "pointwise MLP"),
                     ("k15_l64_syn_r500_g1", "token model (64 slots, 15k steps)")):
        r = runs(tag)
        if r:
            lines.append(row(lab, [x["scores"] for x in r[:1 if tag == "pointwise_mlp" else None]]))
elif args.region == "synthetic":
    p = os.path.join(BASE, "fixed_baselines", "summary.json")
    if os.path.exists(p):
        fb = json.load(open(p))["baselines"]
        for name, lab in (("climatology", "climatology"), ("nearest_profile", "nearest profile"),
                          ("oi", "OI, tuned on this cohort")):
            lines.append(row(lab, [fb[name]["scores"]], n=1))
else:
    for tag, lab in (("real_exact_r500_g1", "token model, anomaly=exact; different evaluation fingerprint (981735)"),
                     ("lno_sla", "token model + SLA (1°, monthly)"),
                     ("backbone_setconv", "SetConv U-Net, profiles only"),
                     ("setconv_sla", "SetConv U-Net + SLA (1°, monthly)"),
                     ("setconv_surface", "SetConv U-Net + SST, SLA, SSS (1°, monthly)")):
        r = runs(tag, os.path.join(ROOT, "outputs", "audit", "global"))
        if r:
            lines.append(row(lab, [x["scores"] for x in r]))

# ---- anchored runs
tags = (args.tags.split(",") if args.tags else
        sorted(os.path.basename(os.path.dirname(p)) for p in glob.glob(os.path.join(BASE, "anc_*", ""))))
detail = []
for tag in tags:
    r = runs(tag)
    if not r:
        continue
    s0 = r[0]
    fg_scores = [x["first_guess"]["scores"] for x in r if "scores" in x["first_guess"]]
    if fg_scores:
        lines.append(row(f"`{tag}`: matched {s0['first_guess']['kind']} first guess only", fg_scores))
    lab = f"`{tag}`: first guess {s0['first_guess']['kind']}, weights {s0['weights']}"
    lines.append(row(lab, [x["scores"] for x in r]))
    detail.append(f"\n`{tag}` seed {s0['seed']}: {s0['params']} parameters in the analysis, "
                  f"best step {s0['best_step']} of {s0['steps']}, {s0['runtime_s']:.0f} s")
    for name, v in s0.get("learned", {}).items():
        detail.append(f"  {name:6s} " + "  ".join(
            f"{ch} " + " ".join(f"{b}:{x:.3g}" for b, x in v[ch].items()) for ch in CH))
    if s0.get("history"):
        detail.append("  validation J TEMP by step: " + ", ".join(
            f"{h['step']}:{h['validation/TEMP_J']:.4f}" for h in s0["history"]))
    d = s0["scores"]["development"]
    detail.append("  development rmse z by band: " + "  ".join(
        f"{ch} " + "/".join(f"{x:.3f}" for x in d[ch]["by_band_z"].values()) for ch in CH))

print("\n".join(lines))
if args.detail:
    print("\n".join(detail))
if args.write:
    name = f"anchored_fusion_{args.region}{'_' + args.subdir if args.subdir else ''}.md"
    out = os.path.join(ROOT, "reports", "real_data" if args.region == "global" else "synthetic", name)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"\nwrote {out}")
