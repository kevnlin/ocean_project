def f(x, n=3):
    return "—" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{n}f}"


def md_table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def summary(tag, seed):
    p = os.path.join(OUTD, tag, f"summary_seed{seed}.json")
    return json.load(open(p)) if os.path.exists(p) else None


def history(tag, seed=1234):
    p = os.path.join(OUTD, tag, "history.jsonl")
    if not os.path.exists(p):
        return []
    return [r for r in map(json.loads, open(p)) if r.get("seed", seed) == seed]


def val(tag, seed, split, ch, key="rmse_physical"):
    s = summary(tag, seed)
    try:
        return float(s["scores"][split][ch][key])
    except (TypeError, KeyError):
        return None


def macro_j(tag, seed, split):
    js = [val(tag, seed, split, ch, "J") for ch in CH]
    return None if None in js else float(np.mean(js))


def seeds_done(tag):
    return [s for s in SEEDS if summary(tag, s) is not None]


def mean_sd(xs):
    xs = [x for x in xs if x is not None]
    if not xs:
        return "—"
    if len(xs) == 1:
        return f"{xs[0]:.4f}"
    return f"{np.mean(xs):.4f} ± {np.std(xs, ddof=1):.4f}"


def paired(tag, ref, split, ch, key="rmse_physical"):
    """Per-seed tag - ref on the seeds both have: (mean, sd, n)."""
    d = [val(tag, s, split, ch, key) - val(ref, s, split, ch, key)
         for s in SEEDS if val(tag, s, split, ch, key) is not None
         and val(ref, s, split, ch, key) is not None]
    if not d:
        return None
    return float(np.mean(d)), (float(np.std(d, ddof=1)) if len(d) > 1 else float("nan")), len(d)


def fmt_pair(p, n=4):
    if p is None:
        return "—"
    m, sd, k = p
    return f"{m:+.{n}f}" + ("" if not np.isfinite(sd) else f" ± {sd:.{n}f}") + f" (n={k})"


def band_mean(per_level):
    a = np.asarray(per_level, float)
    return [float(np.nanmean(a[(LEV > lo) & (LEV <= hi)] if lo else a[LEV <= hi]))
            for _, lo, hi in BANDS]


