"""The paper's tables on the sealed tests, from the results.json files 109 and 113 wrote once.

Same rows as ``118_validation_tables.py``; reads the results, scores nothing. For every row: RMSE at
leads 0, 1, 3, 6 (temperature degC / salinity PSU, mean ± sd over seeds, every cell of the test
years), and the temperature CRPS and 95 % coverage at leads 0 and 6 with the raw spread -> the
spread calibrated on the selection years (``116``); then the persisted OI and the climatology on the
same cells.

  .venv/bin/python experiments/synthetic/120_sealed_tables.py   # writes reports/paper/sealed_tables_20261020.md
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location("tables118", ROOT / "experiments/synthetic/118_validation_tables.py")
tables = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tables)

REPORT = ROOT / "reports/paper/sealed_tables_20261020.md"
RESULTS = {"cesm2": ROOT / "outputs/cesm2_test_20261019/results.json",
           "real": ROOT / "outputs/real_global_20261019/sealed/results.json"}
LEADS = tables.LEADS


def mean_sd(values, digits=4):
    values = np.asarray(values, float)
    return f"{values.mean():.{digits}f}" + (f" ± {values.std(ddof=1):.{digits}f}" if len(values) > 1 else "")


def table(title, groups, results):
    by_path = {entry["checkpoint"]: entry["by_lead"] for entry in results["entries"]}
    lines = [f"## {title}", "",
             "| Row | lead 0 | lead 1 | lead 3 | lead 6 | T CRPS lead 0 / 6 (raw → calibrated) | T 95 % coverage lead 0 / 6 |",
             "|---|---|---|---|---|---|---|"]
    first = None
    for group, rows in groups.items():
        lines.append(f"| **{group}** | | | | | | |")
        for name, folder, tag in rows:
            scored = [by_path[p] for p in (str(folder / f"{tag}_s{s}" / f"best_seed{s}.pt") for s in tables.SEEDS)
                      if p in by_path]
            if not scored:
                lines.append(f"| {name} | not registered | | | | | |")
                continue
            first = first or scored[0]
            rmse = lambda l, ch: mean_sd([r[l]["all"][ch]["model"]["rmse"] for r in scored])
            leads = " | ".join(f"{rmse(l, 'TEMP')} / {rmse(l, 'SALT')}" for l in LEADS)
            pick = lambda l, block, key: np.mean([r[l]["all"]["TEMP"][block][key] for r in scored])
            crps = " / ".join(f"{pick(l, 'model', 'crps'):.4f} → {pick(l, 'model_calibrated', 'crps'):.4f}" for l in ("0", "6"))
            coverage = " / ".join(f"{pick(l, 'model', 'coverage_95'):.2f} → {pick(l, 'model_calibrated', 'coverage_95'):.2f}"
                                  for l in ("0", "6"))
            seeds = f" ({len(scored)}/3)" if len(scored) < 3 else ""
            lines.append(f"| {name}{seeds} | {leads} | {crps} | {coverage} |")
    if first is not None:
        for label, key in (("Persisted OI (same cells)", "persisted_oi"), ("Climatology (same cells)", "climatology")):
            cells = " | ".join(" / ".join(f"{first[l]['all'][ch][key]['rmse']:.4f}" for ch in ("TEMP", "SALT")) for l in LEADS)
            lines.append(f"| {label} | {cells} | | |")
    return lines + [""]


def main():
    lines = ["# Sealed test tables", "",
             "Generated by `experiments/synthetic/120_sealed_tables.py` from the results 109 and 113 wrote once. RMSE "
             "temperature degC / salinity PSU, mean ± sd over seeds 1234-1236, every cell of the test years. CRPS and "
             "coverage: temperature, raw spread → spread calibrated on the selection years (`116`).", ""]
    for test, title, groups in (("cesm2", "CESM2 OSSE, sealed test 2006-2007", tables.CESM2),
                                ("real", "Real Argo + OISST/OISSS/DUACS SLA, sealed test 2022-2023", tables.REAL_ROWS)):
        if RESULTS[test].exists():
            lines += table(title, groups, json.loads(RESULTS[test].read_text()))
        else:
            lines += [f"## {title}", "", "not scored yet", ""]
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
