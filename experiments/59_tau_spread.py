"""How much does the DFS evidence estimate actually vary on real Argo input?

Tables 1-3 keep finding DFS, Uniform and Count within seed noise of each other.
There are two very different reasons that can happen:

  1. the evidence estimate is varying across observations and the model simply
     cannot convert that into accuracy, or
  2. the evidence estimate is nearly CONSTANT, in which case DFS and Uniform are
     computing almost the same thing and the null is arithmetic, not empirical.

Only (2) is checkable without training anything: tau is a property of the
observations and the encoder, not of a fitted model.  This measures its spread
directly, so the interpretation of the null rests on a number rather than on an
assumption about which of the two is happening.

Weights are untrained at a fixed seed. That is deliberate -- the question is
what the evidence estimator sees in the DATA, and a trained checkpoint would
confound that with whatever the run happened to learn.

  .venv/bin/python experiments/59_tau_spread.py
"""
from __future__ import annotations

import argparse, json, os, sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))
import warnings; warnings.filterwarnings("ignore")

import numpy as np
import torch

from ocean_tokenizer import protocol as P
from ocean_tokenizer.argo_obs import ArgoCohort, ArgoNorm, _select_profiles
from ocean_tokenizer.fusion import build_fusion_model

ap = argparse.ArgumentParser()
ap.add_argument("--regions", nargs="+", default=["gulfstream", "npac_gyre"])
ap.add_argument("--densities", nargs="+", type=int, default=[24, 128])
ap.add_argument("--split", default="development")
ap.add_argument("--months", type=int, default=12)
ap.add_argument("--seed", type=int, default=1234)
args = ap.parse_args()

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
out: dict = {}
rows: list = []

for region in args.regions:
    c = ArgoCohort.load(os.path.join(ROOT, "data", "argo_cohort",
                                     f"{region}_ext.nc"))
    norm = ArgoNorm.fit(c, "train")

    class _Grid:
        depth = c.levels

    months = [int(m) for m in c.months_in(args.split)][: args.months]
    for n in args.densities:
        net = build_fusion_model("d4rt", _Grid(), d_model=64, n_latent=32,
                                 n_heads=4, n_self_blocks=2, seed=0,
                                 n_dec_blocks=2, max_lead=6)
        net.eval()
        taus, ntok = [], []
        for mo in months:
            sel = _select_profiles(
                c, c.month(mo, float_split="cohort_float"), n,
                np.random.default_rng([args.seed, mo, 0]))
            if sel.size == 0:
                continue
            prof = np.stack([norm.z("TEMP", c.TEMP[sel]),
                             norm.z("SALT", c.SALT[sel])], axis=1)
            t = lambda a, d=torch.float32: torch.as_tensor(a, dtype=d)
            obs = {"profiles": dict(
                prof=t(prof)[None], lat=t(c.lat[sel])[None],
                lon=t(c.lon[sel])[None], month=t([mo % 12 + 1], torch.long))}
            with torch.no_grad():
                tok = net.encode(obs, batch=1, device="cpu")
                net.fuse(tok)
            live = tok.mask[0]
            taus.append(net.last_evidence["tau"][0][live].numpy())
            ntok.append(int(live.sum()))
        if not taus:
            continue
        a = np.concatenate(taus)
        d = {"n_profiles": n, "n_months": len(taus),
             "tokens_per_month": float(np.mean(ntok)),
             "mean": float(a.mean()), "sd": float(a.std()),
             "cv": float(a.std() / max(a.mean(), 1e-9)),
             "min": float(a.min()), "p05": float(np.percentile(a, 5)),
             "median": float(np.median(a)), "max": float(a.max()),
             "max_over_min": float(a.max() / max(a.min(), 1e-9)),
             "frac_below_0.9": float((a < 0.9).mean())}
        out.setdefault(region, []).append(d)
        rows.append((region, d))
        print(f"{region:12s} n={n:4d}  tokens/mo={d['tokens_per_month']:6.0f}  "
              f"tau mean={d['mean']:.4f} sd={d['sd']:.4f} cv={d['cv']:.3f}  "
              f"min={d['min']:.4f} max/min={d['max_over_min']:.1f}x  "
              f"frac<0.9={d['frac_below_0.9']:.2f}", flush=True)

L = ["# DFS evidence spread on real Argo input", "",
     "_Generated by `experiments/59_tau_spread.py`. Untrained weights at a "
     "fixed seed: tau is a property of the observations and the encoder, so a "
     "trained checkpoint would only confound it with what a run learned._", "",
     "`tau` is the per-token evidence mass. Where it is flat, DFS and Uniform "
     "are computing nearly the same thing and any null between them is "
     "arithmetic rather than empirical.", "",
     "| region | profiles/mo | tokens/mo | mean | sd | CV | min | max/min | "
     "frac τ<0.9 |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
for region, d in rows:
    L.append(f"| {region} | {d['n_profiles']} | {d['tokens_per_month']:.0f} | "
             f"{d['mean']:.4f} | {d['sd']:.4f} | {d['cv']:.3f} | "
             f"{d['min']:.4f} | {d['max_over_min']:.1f}× | "
             f"{d['frac_below_0.9']:.2f} |")
L += ["", "**Reading it.** A CV near zero means the estimator finds the "
      "observations nearly independent, so it has almost nothing to "
      "downweight — DFS ≈ Uniform follows by construction and says nothing "
      "about whether evidence weighting helps when redundancy is present. A "
      "large spread means the mechanism is active, and a null in the accuracy "
      "tables under those conditions is a real negative result about the "
      "mechanism rather than an artefact of the input density.", ""]

os.makedirs(os.path.join(ROOT, "reports"), exist_ok=True)
p_md = os.path.join(ROOT, "reports", "tau_spread.md")
open(p_md, "w").write("\n".join(L))
p_js = os.path.join(ROOT, "outputs", "tau_spread.json")
os.makedirs(os.path.dirname(p_js), exist_ok=True)
json.dump(out, open(p_js, "w"), indent=1)
print(f"\nwrote {p_md}\nwrote {p_js}")
